// Writes docs/<name>-messages.md from examples/<name>/. Run: npm run scenarios
import { readFile, writeFile } from 'node:fs/promises';
import { load, compress } from '../cli/node-protocol.mjs';
import { loadScenario, verbosity } from '../lib/scenario.mjs';

const readExample = async (f) => JSON.parse(await readFile(`examples/${f}`, 'utf8'));
const pct = (a, b) => `${Math.round((100 * a) / b)}%`;

export async function render(name) {
  const protocol = await load();
  const s = await loadScenario(protocol, readExample, name, compress);
  const bad = s.rows.filter((r) => r.message && !r.ok);
  if (bad.length) throw new Error(bad.map((r) => `${r.file}: ${r.errors.join('; ')}`).join('\n'));
  const out = [`# ${s.title}: the messages`, '',
    `Generated by \`npm run scenarios\` from \`examples/${name}/\`. Do not edit by hand.`, '',
    s.source, '',
    'Every message below is a real example file, checked against its definition by `npm test`.',
    'Sizes are bytes: minified JSON, then deflate (level 9). GAP marks something the flow needs that the protocol does not have yet.', ''];
  for (const [branch, label] of Object.entries(s.branches)) {
    out.push(`## ${label}`, '', '| # | From → To | Message | Why | Minified | Deflate |', '|---|---|---|---|---|---|');
    for (const r of s.rows.filter((r) => r.branch === branch)) {
      if (r.gap) out.push(`| — | | **GAP: ${r.gap}** | ${r.why} | | |`);
      else out.push(`| ${r.file.slice(0, 2)} | ${r.from} → ${r.to} | [\`${r.message.type}\`](../examples/${name}/${r.file}) | ${r.why} | ${r.bytes} | ${r.compressed} |`);
    }
    out.push('');
    for (const r of s.rows.filter((r) => r.branch === branch && r.message))
      out.push(`<details><summary>${r.file}</summary>`, '', '```json', JSON.stringify(r.message, null, 2), '```', '', '</details>', '');
  }
  const v = verbosity(s.rows);
  out.push('## Observations on verbosity', '',
    `${v.messages} messages, ${v.total} bytes minified, ${v.compressed} bytes if each is deflated on its own.`, '',
    `The header (\`type\`, \`time\`, \`seq\`, \`asset_id\`) is ${pct(v.fields.filter((f) => ['type', 'time', 'seq', 'asset_id'].includes(f.path)).reduce((a, f) => a + f.bytes, 0), v.total)} of all bytes. Field names, quotes and punctuation are ${pct(v.keyBytes, v.total)}; the values themselves are the rest.`, '',
    'Deflate saves little on one small message, because there is little repetition inside it. Compressing many messages together would find the repeated field names.', '',
    'Where the bytes go (each field summed across every message):', '', '| Field | Times | Bytes | Share |', '|---|---|---|---|');
  for (const f of v.fields.slice(0, 10)) out.push(`| \`${f.path}\` | ${f.count} | ${f.bytes} | ${pct(f.bytes, v.total)} |`);
  out.push('', 'Longest single fields:', '', '| Message | Field | Bytes |', '|---|---|---|');
  for (const f of v.longest.slice(0, 6)) out.push(`| ${f.file} | \`${f.path}\` | ${f.bytes} |`);
  out.push('');
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const name of (await readExample('index.json')).filter((n) => !n.startsWith('proposals/'))) {
    const path = `docs/${name}-messages.md`;
    await writeFile(path, await render(name));
    console.log(`Wrote ${path}`);
  }
}
